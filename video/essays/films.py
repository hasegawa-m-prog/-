def sentences_of(film):
    blob = "".join(p["text"] for p in film["phrases"])
    parts = []
    buf = ""
    for ch in blob:
        buf += ch
        if ch == "。":
            parts.append(buf)
            buf = ""
    if buf:
        parts.append(buf)
    return parts, blob


def validate(film):
    errors = []
    sentences, blob = sentences_of(film)
    for sent in sentences:
        n = len(sent)
        if not 15 <= n <= 35:
            errors.append(f"sentence {n} chars: {sent}")
    for word in BANNED:
        if word in blob:
            errors.append(f"banned: {word}")
    if "私は" in blob or "僕" in blob:
        errors.append("first person should be 私たち")
    n = len(blob)
    if not 300 <= n <= 340:
        errors.append(f"total chars {n} (want 300-340)")
    return errors, n, sentences


def validate_all():
    ok = True
    for film in FILMS:
        errors, n, sentences = validate(film)
        print(f"\n== {film['id']} {film['title']}  {n} chars / {len(film['phrases'])} phrases / {len(sentences)} sentences")
        if errors:
            ok = False
            for err in errors:
                print("  !", err)
        else:
            print("  ok")
    return ok


