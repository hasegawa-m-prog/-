def P(text, sub, scene, action, act, slow=False, brk=False, who=0):
    lines = sub.split("／")
    if not 1 <= len(lines) <= 2:
        raise ValueError(f"subtitle lines: {sub}")
    for line in lines:
        if len(line) > 10:
            raise ValueError(f"subtitle over 10 chars ({len(line)}): {line}")
        if any(ch in line for ch in "、。？！「」"):
            raise ValueError(f"punctuation in subtitle: {line}")
    return {
        "text": text,
        "sub": lines,
        "scene": scene,
        "action": action,
        "act": act,
        "slow": slow,
        "break": brk,
        "who": who,
    }


